-- 1. 군사용어 및 약어 테이블 (기본 사전 + 사용자 제보 용어)
CREATE TABLE IF NOT EXISTS public.military_terms (
  id TEXT PRIMARY KEY,
  term TEXT NOT NULL,
  abbr TEXT NOT NULL,
  english TEXT DEFAULT '',
  hanja TEXT DEFAULT '',
  category TEXT NOT NULL,
  importance TEXT NOT NULL DEFAULT '실무 빈출',
  definition TEXT NOT NULL,
  practical_tip TEXT DEFAULT '',
  example TEXT DEFAULT '',
  related TEXT[] DEFAULT '{}',
  author TEXT DEFAULT '기본 교범',
  likes INTEGER DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. 선배 간부 실무 팁 / 한줄 노하우 공유 테이블
CREATE TABLE IF NOT EXISTS public.term_tips (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  term_id TEXT NOT NULL,
  author_name TEXT NOT NULL DEFAULT '익명 초급간부',
  tip_content TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. 초급간부 역량 테스트 퀴즈 리더보드 테이블
CREATE TABLE IF NOT EXISTS public.quiz_scores (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_name TEXT NOT NULL,
  unit_branch TEXT DEFAULT '육군 보병',
  score INTEGER NOT NULL,
  total_questions INTEGER NOT NULL,
  accuracy INTEGER NOT NULL,
  category TEXT DEFAULT '전체',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Row Level Security (RLS) 활성화 및 공개 읽기/쓰기 정책 (포트폴리오·학습용 데모)
ALTER TABLE public.military_terms ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.term_tips ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.quiz_scores ENABLE ROW LEVEL SECURITY;

-- 기존 정책이 있을 경우 안전하게 재생성
DROP POLICY IF EXISTS "Allow public read military_terms" ON public.military_terms;
DROP POLICY IF EXISTS "Allow public insert military_terms" ON public.military_terms;
DROP POLICY IF EXISTS "Allow public update likes military_terms" ON public.military_terms;

CREATE POLICY "Allow public read military_terms"
  ON public.military_terms FOR SELECT USING (true);
CREATE POLICY "Allow public insert military_terms"
  ON public.military_terms FOR INSERT WITH CHECK (true);
CREATE POLICY "Allow public update likes military_terms"
  ON public.military_terms FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Allow public read term_tips" ON public.term_tips;
DROP POLICY IF EXISTS "Allow public insert term_tips" ON public.term_tips;

CREATE POLICY "Allow public read term_tips"
  ON public.term_tips FOR SELECT USING (true);
CREATE POLICY "Allow public insert term_tips"
  ON public.term_tips FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow public read quiz_scores" ON public.quiz_scores;
DROP POLICY IF EXISTS "Allow public insert quiz_scores" ON public.quiz_scores;

CREATE POLICY "Allow public read quiz_scores"
  ON public.quiz_scores FOR SELECT USING (true);
CREATE POLICY "Allow public insert quiz_scores"
  ON public.quiz_scores FOR INSERT WITH CHECK (true);

